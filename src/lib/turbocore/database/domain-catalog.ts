// TurboCore — Database Domain Catalog (Chapter 8)
//
// TurboCore's database is divided into 14 bounded domains. Each domain owns
// its own schema (via Prisma models) and APIs. This catalog is the single
// source of truth for "what tables exist, in which domain, and why".
//
// Used by:
//   - The admin "Database Architecture" tab to render the domain map
//   - The API layer to validate that queries stay within domain boundaries
//   - Future service extraction (each domain becomes a microservice)

export type DbDomain =
  | "identity"
  | "customers"
  | "wallets"
  | "ledger"
  | "payments"
  | "providers"
  | "capabilities"
  | "countries"
  | "merchants"
  | "compliance"
  | "risk"
  | "fx"
  | "notifications"
  | "audit"
  | "configuration"
  | "analytics"
  | "events";

export interface DomainTable {
  /** Prisma model name (or planned name). */
  model: string;
  /** Human-friendly table name. */
  name: string;
  /** What this table stores. */
  purpose: string;
  /** Whether the table exists in the current Prisma schema. */
  exists: boolean;
  /** Key columns that are indexed. */
  keyIndexes: string[];
  /** Whether this table should be partitioned by time. */
  partitioned: boolean;
  /** Whether this table uses soft-delete (status + deletedAt + deletedBy). */
  softDelete: boolean;
  /** ID prefix for public-facing references. */
  idPrefix: string;
}

export interface DomainInfo {
  id: DbDomain;
  name: string;
  description: string;
  icon: string;
  accent: string;
  order: number;
  /** The golden rule for this domain. */
  principle: string;
  tables: DomainTable[];
}

