export function getDomain(id: DbDomain): DomainInfo | undefined {
  return DOMAINS.find((d) => d.id === id);
}

export function getAllTables(): DomainTable[] {
  return DOMAINS.flatMap((d) => d.tables);
}

export function getTableStats() {
  const all = getAllTables();
  return {
    totalDomains: DOMAINS.length,
    totalTables: all.length,
    existingTables: all.filter((t) => t.exists).length,
    plannedTables: all.filter((t) => !t.exists).length,
    partitionedTables: all.filter((t) => t.partitioned).length,
    softDeleteTables: all.filter((t) => t.softDelete).length,
    tablesByDomain: DOMAINS.map((d) => ({
      domain: d.id,
      name: d.name,
      total: d.tables.length,
      existing: d.tables.filter((t) => t.exists).length,
      planned: d.tables.filter((t) => !t.exists).length,
    })),
  };
}

